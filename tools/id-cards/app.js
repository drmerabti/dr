const FIELD_LABELS = {
  name: 'fieldName', title: 'fieldTitle', phone: 'fieldPhone',
  website: 'fieldWebsite', email: 'fieldEmail', social: 'fieldSocial',
};
function applyFieldVisibility(){
  const used = TEMPLATES[activeTemplate].fields;
  Object.keys(FIELD_LABELS).forEach((key) => {
    const row = document.querySelector(`.field[data-field="${key}"]`);
    if (row) row.classList.toggle('hidden', !used.includes(key));
  });
}

function renderQrInto(container, text, darkColor){
  container.innerHTML = '';
  if (!window.QRCode) return; // مكتبة QRCode.js تُحمَّل من CDN بالموقع الحقيقي فقط
  const qrTarget = document.createElement('div');
  document.body.appendChild(qrTarget);
  new QRCode(qrTarget, {
    text: text || 'https://merabti.com',
    width: 256, height: 256,
    colorDark: darkColor, colorLight: '#FFFFFF',
    correctLevel: QRCode.CorrectLevel.M,
  });
  setTimeout(() => {
    const img = qrTarget.querySelector('img') || qrTarget.querySelector('canvas');
    if (!img) { document.body.removeChild(qrTarget); return; }
    const dataUrl = img.tagName === 'CANVAS' ? img.toDataURL('image/png') : img.src;
    container.dataset.qrDataUrl = dataUrl;
    const overlay = document.createElement('img');
    overlay.src = dataUrl;
    overlay.style.cssText = 'width:100%;height:100%;display:block;';
    container.appendChild(overlay);
    document.body.removeChild(qrTarget);
  }, 60);
}

function positionQrOverlay(overlayEl){
  const tpl = TEMPLATES[activeTemplate];
  const [vw, vh] = tpl.viewBox;
  const box = tpl.qrBox;
  const pct = (v, total) => (v / total * 100) + '%';
  overlayEl.style.position = 'absolute';
  overlayEl.style.left = pct(box.x, vw);
  overlayEl.style.top = pct(box.y, vh);
  overlayEl.style.width = pct(box.w, vw);
  overlayEl.style.height = pct(box.h, vh);
}

function updatePreview(){
  const d = getFormData();
  const tpl = TEMPLATES[activeTemplate];
  $('previewFront').innerHTML = tpl.front(d);
  $('previewBack').innerHTML = tpl.back();

  const backWrap = $('previewBack').closest('.preview-card');
  let overlay = backWrap.querySelector('.qr-overlay');
  if (!overlay) {
    overlay = document.createElement('div');
    overlay.className = 'qr-overlay';
    backWrap.appendChild(overlay);
  }
  positionQrOverlay(overlay);
  const qrText = d.website ? (d.website.startsWith('http') ? d.website : 'https://' + d.website) : 'https://merabti.com';
  renderQrInto(overlay, qrText, tpl.qrDark);
}

