/* ---------- تصدير PDF (وجه + ظهر) عبر svg2pdf — رسم متجهي، بدون التقاط صور ---------- */
async function exportPdf(){
  const btn = $('downloadBtn');
  const original = btn.textContent;
  btn.disabled = true;
  btn.textContent = 'جارٍ إنشاء الملف…';
  try {
    const tpl = TEMPLATES[activeTemplate];
    const [w, h] = tpl.viewBox;
    const { jsPDF } = window.jspdf;
    const doc = new jsPDF({ unit: 'pt', format: [w, h], orientation: 'landscape' });

    const frontEl = $('previewFront').querySelector('svg');
    await doc.svg(frontEl, { x: 0, y: 0, width: w, height: h });

    doc.addPage([w, h], 'landscape');
    const backEl = $('previewBack').querySelector('svg');
    await doc.svg(backEl, { x: 0, y: 0, width: w, height: h });

    const overlay = $('previewBack').closest('.preview-card').querySelector('.qr-overlay');
    const qrDataUrl = overlay && overlay.dataset.qrDataUrl;
    if (qrDataUrl) {
      const box = tpl.qrBox;
      doc.addImage(qrDataUrl, 'PNG', box.x, box.y, box.w, box.h);
    }

    doc.save('business-card.pdf');
  } catch (err) {
    console.error(err);
    alert('حدث خطأ أثناء إنشاء الملف، حاول مرة أخرى.');
  } finally {
    btn.disabled = false;
    btn.textContent = original;
  }
}

